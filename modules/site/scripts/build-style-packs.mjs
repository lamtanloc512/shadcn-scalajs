import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import postcss from "postcss";
import tailwind from "@tailwindcss/postcss";

/*
 * Emits one compiled stylesheet per style pack instead of bundling all eight into the main CSS.
 *
 * Every pack ships ~1,670 lines of rules keyed off [data-style-pack="<name>"], but only one pack is ever active.
 * Chromium buckets rules by their rightmost simple selector, so keeping all eight in one sheet means every element
 * carrying, say, .cn-button is matched against eight copies of that rule on every full-document style recalc — and
 * anything that promotes an element to the top layer (dialog.showModal) forces exactly that. Measured on
 * /blocks/dashboard-01: 52ms per modal open with all packs bundled, 4ms with the inactive packs removed.
 *
 * Each pack file is compiled standalone against globals.css via Tailwind's @reference, which supplies the theme so
 * @apply resolves without re-emitting the base layers.
 */

const here = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(here, "../../..");
const siteRoot = join(projectRoot, "modules/site");
const shadcnRoot = join(projectRoot, "vendor/shadcn-source/styles");
const entryDir = join(siteRoot, "src/styles/packs");
const outDir = join(siteRoot, "public/styles");

export const packs = ["nova", "vega", "maia", "lyra", "mira", "luma", "sera", "rhea"];

export function shadcnPackBlock(pack) {
  const file = join(shadcnRoot, `style-${pack}.css`);
  return readFileSync(file, "utf8").replaceAll(`.style-${pack}`, `[data-style-pack="${pack}"]`);
}

function entrySource(pack) {
  return [
    `/* Generated by scripts/build-style-packs.mjs — do not edit. */`,
    // Pulls in the theme/utility context only; @reference emits no CSS of its own.
    `@reference "../globals.css";`,
    ``,
    // Preset rules stay unlayered so they still beat utilities the way the shadcn v4 stylesheet does.
    shadcnPackBlock(pack),
    ``,
  ].join("\n");
}

async function build() {
  rmSync(entryDir, { recursive: true, force: true });
  mkdirSync(entryDir, { recursive: true });
  mkdirSync(outDir, { recursive: true });

  const processor = postcss([tailwind()]);
  for (const pack of packs) {
    const entryPath = join(entryDir, `${pack}.css`);
    const outPath = join(outDir, `pack-${pack}.css`);
    writeFileSync(entryPath, entrySource(pack));
    const result = await processor.process(entrySource(pack), { from: entryPath, to: outPath });
    writeFileSync(outPath, result.css);
    const kb = (Buffer.byteLength(result.css) / 1024).toFixed(0);
    console.log(`  pack-${pack}.css  ${kb} kB`);
  }
  console.log(`Built ${packs.length} style packs -> public/styles`);
}

// Guarded so build-webcomponents.mjs can import the pack helpers without triggering a full pack build.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await build();
