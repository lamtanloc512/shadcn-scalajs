import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import * as esbuild from "esbuild";
import postcss from "postcss";
import tailwind from "@tailwindcss/postcss";

import { basecoatPackBody, shadcnPackBlock } from "./build-style-packs.mjs";

/*
 * Builds public/sc-components.js (the Sc* custom elements flattened into one ES module) and public/sc-components.css
 * (Tailwind output rewritten so :root tokens also apply to :host, so they resolve inside a shadow root).
 *
 * One style pack is baked in. Components like Accordion and the menus get all of their padding, borders and type from
 * the pack layer, not from their own utilities, so a bundle built from globals.css alone renders them as bare text.
 * The baked pack is what the bundle falls back to; selecting any pack at runtime makes ScPacks fetch that pack's own
 * stylesheet instead, which is why the fallback yields to an explicit selection rather than applying unconditionally.
 */

const here = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(here, "../../..");
const siteRoot = join(projectRoot, "modules/site");
const stylesDir = join(siteRoot, "src/styles");
const outDir = join(siteRoot, "public");
const scalaVersion = "3.5.2";

const fast = process.env.SC_WC_MODE === "fast";
const linkTask = fast ? "webcomponents/fastLinkJS" : "webcomponents/fullLinkJS";
const linkDir = join(
  projectRoot,
  "modules/webcomponents/target",
  `scala-${scalaVersion}`,
  fast ? "webcomponents-fastopt" : "webcomponents-opt"
);

function link() {
  if (process.env.SC_WC_SKIP_LINK === "1") {
    if (!existsSync(join(linkDir, "main.js"))) throw new Error(`SC_WC_SKIP_LINK=1 but no linker output at ${linkDir}`);
    return;
  }
  execFileSync("sbt", ["-batch", linkTask], { cwd: projectRoot, stdio: "inherit" });
}

async function buildJs() {
  const outFile = join(outDir, "sc-components.js");
  await esbuild.build({
    entryPoints: [join(linkDir, "main.js")],
    outfile: outFile,
    bundle: true,
    format: "esm",
    target: "es2020",
    minify: !fast,
    legalComments: "none",
    logLevel: "warning"
  });
  return outFile;
}

/*
 * Two rewrites make the sheet work inside a shadow root:
 *   :root                      also applies to :host, so the design tokens are reachable
 *   [data-style-pack="<pack>"]  also matches the shadow-root wrapper when the document names no pack, so components are
 *                               styled out of the box. `:not([data-style-pack])` keeps it a fallback: once a pack is
 *                               selected the wrapper carries its name and the fetched pack's own rules take over.
 */
function shadowScope(packName) {
  const packSelector = `[data-style-pack="${packName}"]`;
  const fallback = '[data-slot="sc-theme-host"]:not([data-style-pack])';
  return {
    postcssPlugin: "sc-shadow-scope",
    OnceExit(root) {
      root.walkRules(rule => {
        const selectors = rule.selectors;
        const next = [...selectors];
        if (selectors.includes(":root") && !selectors.includes(":host")) next.push(":host");
        for (const selector of selectors) {
          if (selector.includes(packSelector)) next.push(selector.replaceAll(packSelector, fallback));
        }
        if (next.length !== selectors.length) rule.selectors = next;
      });
    }
  };
}

const pack = process.env.SC_WC_PACK ?? "nova";

const cssEntry = [
  "/* Generated by scripts/build-webcomponents.mjs — do not edit. */",
  '@import "./globals.css";',
  '@source "../../../webcomponents/src/main/scala/**/*.scala";',
  "",
  "@layer components {",
  `  [data-style-pack="${pack}"] {`,
  basecoatPackBody(pack),
  "  }",
  "}",
  "",
  shadcnPackBlock(pack),
  "",
  // Lets ScStyles read back which pack is baked in, so it only fetches a pack sheet when a different one is selected.
  `@layer base { :root { --sc-pack: "${pack}"; } }`,
  ""
].join("\n");

async function buildCss() {
  const outFile = join(outDir, "sc-components.css");
  const result = await postcss([tailwind(), shadowScope(pack)]).process(cssEntry, {
    from: join(stylesDir, "sc-components.entry.css"),
    to: outFile
  });
  writeFileSync(outFile, result.css);
  return outFile;
}

function report(label, file) {
  console.log(`  ${label}  ${(statSync(file).size / 1024).toFixed(0)} kB`);
}

mkdirSync(outDir, { recursive: true });
link();
const js = await buildJs();
const css = await buildCss();
report("sc-components.js ", js);
report("sc-components.css", css);

const emitted = readFileSync(css, "utf8");
if (!emitted.includes(":host")) throw new Error("sc-components.css has no :host rules — tokens would not resolve");
if (!emitted.includes("cn-accordion-trigger")) throw new Error(`sc-components.css is missing the ${pack} pack layer`);
console.log(`Built web component bundle (${pack} pack) -> modules/site/public`);
